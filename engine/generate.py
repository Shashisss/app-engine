"""Render a spec into a runnable Streamlit app on disk."""

from __future__ import annotations

import json
from pathlib import Path

from jinja2 import Environment, FileSystemLoader, select_autoescape

from .spec import AppSpec, slugify  # noqa: F401  (re-exported for the UI)

ROOT = Path(__file__).resolve().parents[1]
TEMPLATE_DIR = ROOT / "templates"
APPS_DIR = ROOT / "apps"

_env = Environment(
    loader=FileSystemLoader(str(TEMPLATE_DIR)),
    autoescape=select_autoescape(enabled_extensions=("html",), default=False),
    keep_trailing_newline=True,
)

TEMPLATES = {"records": "records_app.py.j2", "calculator": "calculator_app.py.j2"}


def app_dir(slug: str) -> Path:
    return APPS_DIR / slug


def unique_slug(slug: str) -> str:
    candidate, n = slug, 2
    while app_dir(candidate).exists():
        candidate = f"{slug}-{n}"
        n += 1
    return candidate


def render(spec: AppSpec) -> str:
    template_name = TEMPLATES.get(spec.kind)
    if template_name is None:
        raise ValueError(f"no template for kind {spec.kind!r}")
    template = _env.get_template(template_name)
    payload = spec.as_dict()
    return template.render(spec_json=json.dumps(payload, indent=2, ensure_ascii=False))


def build(spec: AppSpec, force_slug: str | None = None) -> Path:
    """Write the generated app and return its directory."""
    slug = force_slug or unique_slug(spec.slug)
    spec.slug = slug
    target = app_dir(slug)
    target.mkdir(parents=True, exist_ok=True)

    source = render(spec)
    (target / "app.py").write_text(source, encoding="utf-8")

    readme = (
        f"# {spec.name}\n\n"
        f"{spec.description}\n\n"
        f"Generated by the App Engine from: _{spec.idea or 'manual spec'}_\n\n"
        f"- kind: `{spec.kind}`\n"
        f"- entity: `{spec.entity}`\n"
        f"- fields: {', '.join(f.name for f in spec.fields)}\n\n"
        f"Run it standalone:\n\n```bash\nstreamlit run app.py\n```\n"
    )
    (target / "README.md").write_text(readme, encoding="utf-8")
    (target / "spec.json").write_text(json.dumps(spec.as_dict(), indent=2), encoding="utf-8")
    return target
